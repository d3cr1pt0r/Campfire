// Regenerates shared/emojis.js from Emojibase (MIT). Run with `node scripts/emoji-data.mjs`
// after updating the bundled Noto font, so the picker offers the emoji the font can draw.
import { writeFile } from 'node:fs/promises';
import prettier from 'prettier';

const version = '18.0.0';
const source = (file) =>
    fetch(`https://cdn.jsdelivr.net/npm/emojibase-data@${version}/en/${file}`).then((response) => {
        if (!response.ok) throw new Error(`${file}: ${response.status}`);
        return response.json();
    });
const [data, messages, github] = await Promise.all([
    source('data.json'),
    source('messages.json'),
    source('shortcodes/github.json'),
]);
// Skin tones and hair components only make sense inside other emoji.
const groups = messages.groups.filter((group) => group.key !== 'component');
const words = (list) => [list ?? []].flat().join(' ').toLowerCase();
const entry = (emoji) =>
    // Each emoji is "character|name|keywords|shortcodes".
    [
        emoji.emoji,
        emoji.label.toLowerCase(),
        words(emoji.tags).replaceAll('|', ''),
        words(github[emoji.hexcode]),
    ].join('|');
const output = `// Generated by scripts/emoji-data.mjs from emojibase-data ${version} (MIT). Do not edit.
export const emojiGroups = ${JSON.stringify(
    groups.map((group) => ({
        name: group.message[0].toUpperCase() + group.message.slice(1),
        emoji: data
            .filter((emoji) => emoji.group === group.order)
            .sort((a, b) => a.order - b.order)
            .map(entry),
    })),
)}.map((group) => ({
    name: group.name,
    emoji: group.emoji.map((line) => {
        const [emoji, name, keywords, shortcodes] = line.split('|');
        return { emoji, name, keywords, shortcodes: shortcodes ? shortcodes.split(' ') : [] };
    }),
}));
export const emojis = emojiGroups.flatMap((group) => group.emoji.map((item) => item.emoji));
`;
const file = new URL('../shared/emojis.js', import.meta.url);
await writeFile(
    file,
    await prettier.format(output, {
        ...(await prettier.resolveConfig(file)),
        filepath: file.pathname,
    }),
);
